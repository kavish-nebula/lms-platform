import assert from 'node:assert/strict';
import {automationAiLesson, AUTOMATION_AI_SOURCE} from '@/lib/automation-ai-lesson';
import {automationAiStoryboard} from '@/server/adapt/automation-ai-storyboard';
import {validateDirectedPlan} from '@/server/adapt/visual-director';
import type {PersonalizedConcept} from '@/lib/personalized-concept';
import {automationFrames, framesForRecording, matchTopicFrames, TopicVisualLibrary} from '@/lib/topic-visual-assets';
import {conceptSlides} from '@/lib/concept-slides';
const source:PersonalizedConcept={scenes:Array.from({length:7},(_,i)=>({id:`original-${i}`,phase:i<4?'before':'after',visual:'automation',title:'Original',points:['First','Second'],narration:'Source recording.',bridge:'Original bridge.',sourceIds:['M1S1'],objectiveIds:['O1']}))};
const original=JSON.stringify(source), course='dd1fec93-8c51-4f2d-9e0c-943823062c76';
for(const field of ['Finance','Healthcare','Education','Production','Unspecified']) {
 const result=automationAiLesson(source,course,'Automation vs AI',{answers:{field}})!;
 assert.ok(result);
 assert.equal(result.scenes.map(s=>s.id).join(),source.scenes.map(s=>s.id).join());
 assert.deepEqual(result.scenes.map(s=>s.phase),source.scenes.map(s=>s.phase));
 assert.ok(result.scenes.every(s=>s.sourceIds.includes(AUTOMATION_AI_SOURCE)&&s.objectiveIds[0]==='O1'));
 assert.match(result.scenes[1].narration,/PLC/);
 assert.match(result.scenes[3].narration,/70 degrees/);
 assert.match(result.scenes[2].narration,/does not necessarily learn/);
 assert.match(result.scenes[6].narration,/written condition[\s\S]*fixed-rule automation/);
 const chapters=automationAiStoryboard(result.scenes)!;
 assert.equal(new Set(chapters.map(c=>c.kind)).size,7);
 validateDirectedPlan({chapters},result.scenes);
 const words=result.scenes.map(s=>s.narration+' '+s.bridge).join(' ').split(/\s+/).length;
 assert.ok(words<700,`${field}: concise script budget ${words}`);
 if(field==='Healthcare') assert.match(result.scenes[0].narration,/clinic reception/);
 if(field==='Finance') assert.match(result.scenes[0].narration,/accounts payable/);
}
assert.equal(JSON.stringify(source),original);
assert.equal(automationAiLesson(source,'other-course','Automation vs AI',{}),undefined);
assert.equal(automationAiLesson(source,course,'Introduction to LLMs',{}),undefined);
assert.equal(automationAiStoryboard(source.scenes),undefined);
const full:PersonalizedConcept={scenes:[...source.scenes,{...source.scenes[6],id:'original-7'}].map(s=>({...s,sourceIds:['S07c802cc6e85a4e4d627']}))};
const expanded=automationAiLesson(full,'affcb1b6-5539-431c-9a95-cce2bdb26b51','Automation vs AI',{answers:{field:'Finance'}})!;
assert.equal(expanded.scenes.length,8);
assert.match(expanded.scenes[3].narration,/oversized.*sequence stops/);
assert.match(expanded.scenes[4].narration,/50 pounds/);
assert.match(expanded.scenes[4].narration,/92 percent/);
assert.equal(expanded.scenes[3].phase,'before');
assert.equal(expanded.scenes[4].phase,'after');
validateDirectedPlan({chapters:automationAiStoryboard(expanded.scenes)},expanded.scenes);
const hash = automationFrames.recordingSha256;
assert.deepEqual(matchTopicFrames(automationFrames.frames,expanded.scenes,'finance').map(s=>s.frame.id),['plc-ladder','logic-path']);
assert.deepEqual(framesForRecording(automationFrames,'wrong edition'),[]);
const shared = automationFrames.frames[0];
const finance = {...shared, id:'finance-frame', field:'finance'};
const library = TopicVisualLibrary.parse({recordingSha256:hash, frames:[shared,finance]});
const scene = expanded.scenes[1];
const picks = matchTopicFrames(library.frames,[scene],'Finance');
assert.equal(picks[0].frame.id,finance.id);
assert.equal(matchTopicFrames(library.frames,[scene],'healthcare')[0].frame.id,shared.id);
assert.deepEqual(matchTopicFrames([shared,{...shared,id:'ambiguous'}],[scene],''),[]);
assert.deepEqual(matchTopicFrames(automationFrames.frames,[{...scene,narration:'Other teaching.',bridge:scene.narration}],'finance'),[]);
assert.equal(TopicVisualLibrary.safeParse({...library,frames:[{...shared,crop:{x:.8,width:.4,y:0,height:1}}]}).success,false);
const asset = {id:shared.id,label:shared.label,sentence:picks[0].sentence,image:'test-frame'};
const slides = conceptSlides({...scene,selectedVisuals:[asset]});
assert.deepEqual(slides.filter(s=>s.asset).map(s=>s.text),[asset.sentence]);
assert.ok(slides.filter(s=>s.context).every(s=>!s.asset));
console.log('Automation/AI: profile cases, source mappings, scope, cue order and concise teaching passed.');
