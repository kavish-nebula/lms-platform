import assert from 'node:assert/strict';
import { recommendCourses, type RecommendationCourse } from '@/lib/course-recommendations';
import { learnerCourseRecommendations } from '@/server/course-recommendations';
import { getSessionUser } from '@/server/auth';
import { getProfile, listEnrollments, saveProfile } from '@/server/repo';
import { createCreatorDraft } from '@/server/content-creator';
import { EMPTY_BRIEF } from '@/lib/content-creator';
import { closeDb } from '@/server/db/client';

const course = (id: string, title: string, skills: string[], moduleCount = 3): RecommendationCourse => ({ course_id: id, title, skills, moduleCount, tagline: '', goal: '', level: 'Beginner', estimated_hours: 2 });
const catalog = [course('general', 'AI Essentials for Everyday Work', ['Prompting']), course('health', 'AI for Healthcare', ['Clinical documentation']), course('factory', 'AI for Production', ['Manufacturing analytics']), course('agent', 'Build Your First AI Agent', ['Programming', 'API']), course('factory-alias', 'AI for Production', ['Manufacturing'], 1)];
const healthcare = { domain: 'other', domainOther: 'Healthcare', coding: 'none' };
const developer = { domain: 'other', domainOther: 'Software development', coding: 'python' };
assert.equal(recommendCourses(catalog, healthcare)[0].course.course_id, 'health');
assert.equal(recommendCourses(catalog, developer)[0].course.course_id, 'agent');
assert.equal(recommendCourses(catalog, { domain: 'it', coding: 'python' })[0].course.course_id, 'agent');
assert.equal(recommendCourses(catalog.filter(c => c.course_id !== 'health'), healthcare)[0].course.course_id, 'general');
assert(!recommendCourses(catalog, healthcare).some(r => r.course.course_id === 'factory'));
assert.equal(recommendCourses(catalog, { domain: 'manufacturing' })[0].course.course_id, 'factory');
assert.equal(recommendCourses(catalog, { domain: 'manufacturing' }).filter(r => r.course.title === 'AI for Production').length, 1);
assert(recommendCourses(catalog.filter(c => c.course_id !== 'health'), healthcare).every(r => r.basis !== 'field'));
assert(!recommendCourses(catalog.filter(c => c.course_id !== 'health'), healthcare).some(r => r.course.course_id === 'factory'), 'Do not fill suggestions with unrelated sector courses.');
assert(recommendCourses(catalog, {}, ['general']).find(r => r.course.course_id === 'general')?.enrolled);
assert.deepEqual(recommendCourses([], healthcare), []);
assert.deepEqual(recommendCourses(catalog, healthcare), recommendCourses(catalog, healthcare));
assert(!recommendCourses(catalog, {}).some(r => /your stated field|your interest/i.test(r.reason)), 'No invented matches when the profile is empty.');
assert(!('score' in recommendCourses(catalog, healthcare)[0]), 'Internal ranking must not be presented as learner proficiency.');

const user = await getSessionUser();
await saveProfile(user.id, developer, []);
await createCreatorDraft(user.id, { brief: { ...EMPTY_BRIEF, title: 'Unpublished Software Programming Course', subject: 'Software' } });
const before = await getProfile(user.id);
const enrollments = await listEnrollments(user.id);
const result = await learnerCourseRecommendations(user.id);
assert(result.hasProfile);
assert(result.suggestions.length > 0, 'Integration assertions must exercise an actual suggestion.');
assert(!result.suggestions.some(r => r.course.title === 'Unpublished Software Programming Course'));
assert(result.suggestions.every(r => !('modules' in r.course) && !('questions' in r.course)));
assert.deepEqual(await getProfile(user.id), before, 'Suggestions must not rewrite the profile.');
assert.deepEqual(await listEnrollments(user.id), enrollments, 'Suggestions must not enroll learners.');
await closeDb();
console.log('PASS course recommendations: two distinct profiles, matching and fallback reasons, coding preferences, stable ranking, duplicate titles, enrollment labels, unpublished-course exclusion, metadata-only output and read-only learner state.');
