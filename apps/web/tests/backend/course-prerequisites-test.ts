import assert from 'node:assert/strict';
import { prerequisitesFor, prerequisiteSelectionComplete, reviewPrerequisites, prerequisiteEnrollmentAnswers, prerequisiteSuggestions } from '@/lib/course-prerequisites';
import { quickEnrollmentAnswers } from '@/lib/quick-enrollment';
import { normalizeAnswers, profilePart, coursePart } from '@/lib/setup';
import { getCourse, getCourses } from '@/data';
import { getSessionUser } from '@/server/auth';
import { getProfile, listEnrollments } from '@/server/repo';
import { createCreatorDraft } from '@/server/content-creator';
import { EMPTY_BRIEF } from '@/lib/content-creator';
import { EnrolBody } from '@/server/validators';
import { closeDb } from '@/server/db/client';

const base = (await getCourse('ai-agent'))!;
const topics = prerequisitesFor(base);
assert.deepEqual(topics, ['llm','chatbot']);
assert.deepEqual(prerequisitesFor({course_id:'other'}), []);
assert.deepEqual(prerequisitesFor({course_id:'ai-agent',prerequisiteTopics:[]}), []);
assert.deepEqual(prerequisitesFor({course_id:'other',prerequisiteTopics:['chatbot','chatbot']}), ['chatbot']);
assert(!prerequisiteSelectionComplete(topics, {}));
assert(!prerequisiteSelectionComplete(topics, {llm:{familiarity:'familiar'},chatbot:{familiarity:'new'}}));
assert(!prerequisiteSelectionComplete(topics, {llm:{familiarity:'familiar',response:'invented'},chatbot:{familiarity:'new'}}));
const newLearner = {llm:{familiarity:'new' as const},chatbot:{familiarity:'unsure' as const}};
assert(prerequisiteSelectionComplete(topics,newLearner));
assert(reviewPrerequisites(topics,newLearner).every(r=>r.needsIntroduction && r.observed==='not-taken'));
const known = {llm:{familiarity:'familiar' as const,response:'generate'},chatbot:{familiarity:'familiar' as const,response:'unverified'}};
assert(prerequisiteSelectionComplete(topics,known));
assert(reviewPrerequisites(topics,known).every(r=>!r.needsIntroduction && r.observed==='supported'));
const mismatch = {...known,llm:{familiarity:'familiar' as const,response:'database'}};
assert(reviewPrerequisites(topics,mismatch)[0].needsIntroduction,'Stated familiarity must not override an unsupported concept explanation.');
assert.equal(reviewPrerequisites(topics,mismatch)[0].familiarity,'familiar');
assert.equal(reviewPrerequisites(topics,mismatch)[0].observed,'review');
assert(reviewPrerequisites(topics,{...newLearner,llm:{familiarity:'unsure',response:'generate'}})[0].needsIntroduction,'A stale response must not erase a learner’s request for an introduction.');

const llm = {...base,course_id:'llm-intro',title:'Introduction to Large Language Models',learn:['Explain LLMs'],skills:['LLMs'],modules:[{...base.modules[0],module_id:'intro',title:'Large language models'}]};
const chatbot = {...base,course_id:'chatbot-intro',title:'Chatbot Fundamentals',learn:['Explain chatbots'],skills:['Chatbots'],modules:[{...base.modules[0],module_id:'intro',title:'Chatbots'}]};
const production = {...base,course_id:'production',title:'AI for Production',learn:[],skills:['LLMs'],modules:[{...base.modules[0],module_id:'M1',title:'Introduction to LLMs'}]};
const unrelated = {...base,course_id:'unrelated',title:'Healthcare Reporting',learn:[],skills:[],modules:[{...base.modules[0],title:'Charts'}]};
const choices=prerequisiteSuggestions([base,llm,chatbot,production,unrelated],'ai-agent',topics);
assert(!choices.some(c=>c.courseId==='ai-agent'||c.courseId==='unrelated'));
assert(choices.some(c=>c.courseId==='llm-intro'&&c.topics.includes('llm')));
assert(choices.some(c=>c.courseId==='chatbot-intro'&&c.topics.includes('chatbot')));
assert.equal(choices.find(c=>c.courseId==='production')!.href,'/learn/courses/production/M1/reader','An advanced course should point to its relevant introduction, not require the whole course.');
assert.deepEqual(prerequisiteSuggestions([],base.course_id,topics),[]);
assert.equal(prerequisiteSuggestions([llm,{...llm,course_id:'duplicate'}],base.course_id,topics).length,1);
assert(prerequisiteSuggestions([{...production,skills:[]}],base.course_id,topics).some(s=>s.moduleTitle==='Introduction to LLMs'),'A module title can establish an introductory match even when the course skills omit it.');
const manyLlm=[...['A','B','C','D'].map((prefix,i)=>({...llm,course_id:'llm'+i,title:prefix+' LLM Foundations'})),{...chatbot,title:'Z Chatbot Foundations'}];
assert(prerequisiteSuggestions(manyLlm,base.course_id,topics).some(s=>s.topics.includes('chatbot')),'Available foundations for both concepts must survive the three-card limit.');
assert.equal(prerequisiteSuggestions([{...production,modules:[...production.modules,{...production.modules[0],module_id:'M2',title:'Chatbot basics'}]}],base.course_id,topics).length,2,'Separate introductory modules keep their own links and coverage.');

const profile={domain:'healthcare',coding:'none'};
const context=prerequisiteEnrollmentAnswers(profile,topics,mismatch);
assert.deepEqual(profile,{domain:'healthcare',coding:'none'});
assert.equal(context.courseInterview?.length,2);
assert(context.courseInterview?.[0].a.includes('Self-report: familiar')&&context.courseInterview[0].a.includes('needs review'));
assert(!profilePart(context).courseInterview);
assert.equal(coursePart(context).courseInterview?.length,2);
assert.equal(quickEnrollmentAnswers(context,'','','','').courseInterview?.length,2,'Skipping optional goals must retain the prerequisite context.');
assert.equal(normalizeAnswers(context).courseInterview?.length,2);
assert(EnrolBody.safeParse({courseId:'ai-agent',answers:context,supportOverride:'auto',pace:null}).success);
assert.equal(prerequisiteEnrollmentAnswers(context,topics,known).courseInterview?.length,2,'Rechecking replaces the prior context, without duplicate turns.');

const user=await getSessionUser();
await createCreatorDraft(user.id,{brief:{...EMPTY_BRIEF,title:'Unpublished Chatbot Fundamentals',subject:'Chatbots'}});
const before={profile:await getProfile(user.id),enrollments:await listEnrollments(user.id)};
const visible=await getCourses(true,user.id);
assert(!prerequisiteSuggestions(visible,base.course_id,topics).some(s=>s.title==='Unpublished Chatbot Fundamentals'));
assert.deepEqual({profile:await getProfile(user.id),enrollments:await listEnrollments(user.id)},before,'Readiness suggestions do not enroll a learner or change their profile.');
await closeDb();
console.log('PASS prerequisites: explicit scope, separate stated/observed knowledge, newcomer/unsure/correct/incorrect paths, relevant visible courses, module links, no fabricated recommendations, course-only context and no learner writes.');
